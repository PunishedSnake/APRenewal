"""Generate src/buttonicons.h from the game's UI_ButtonIcons.upk: for every Xbox gamepad prompt texture, the
FNV-1a hash of its top mip (as uploaded to D3D), the hash of the matching PS3 prompt in the same package, and
where the PS art goes inside the Xbox texture (the UI draws only the top-left part of most Xbox icons).
Usage: python3 -I buttonicons.py <UI_ButtonIcons.upk> > ../../src/buttonicons.h"""
import sys, struct, zlib, io, re, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from upk import Pkg
from PIL import Image

def props(p, b, o):
    out = {}
    while o < len(b):
        nm = p.names[struct.unpack_from('<i', b, o)[0]]; o += 8
        if nm == 'None': return out, o
        tn = p.names[struct.unpack_from('<i', b, o)[0]]; o += 8
        sz, ai = struct.unpack_from('<ii', b, o); o += 8
        if tn == 'BoolProperty': v = b[o]; o += 4          # UBOOL: 4 bytes in this engine version
        elif tn == 'ByteProperty': v = p.names[struct.unpack_from('<i', b, o)[0]] if sz == 8 else b[o]; o += sz
        elif tn == 'StructProperty': o += 8; v = b[o:o + sz]; o += sz
        elif tn == 'IntProperty': v = struct.unpack_from('<i', b, o)[0]; o += sz
        else: v = b[o:o + sz]; o += sz
        out[nm] = v
    return out, o

def mip0(b, o):
    o += 16                                         # source art bulk data header
    n = struct.unpack_from('<i', b, o)[0]; o += 4
    fl, cnt, sz, off = struct.unpack_from('<IiiI', b, o); o += 16
    raw = b[o:o + sz]; o += sz
    if fl & 2:                                      # zlib-chunked
        q = 16; usz = struct.unpack_from('<i', raw, 12)[0]; blocks = []; got = 0
        while got < usz:
            a, c = struct.unpack_from('<ii', raw, q); q += 8; blocks.append((a, c)); got += c
        data = b''
        for a, c in blocks: data += zlib.decompress(raw[q:q + a]); q += a
    else: data = raw
    w, h = struct.unpack_from('<ii', b, o)
    return w, h, data

def full(p, i):
    e = p.exports[i]; n = e['name']; o = e['outer']
    while o > 0: n = p.exports[o - 1]['name'] + '.' + n; o = p.exports[o - 1]['outer']
    return n

def fnv(b):
    h = 0x811C9DC5
    for x in b: h = ((h ^ x) * 0x01000193) & 0xffffffff
    return h

def dxt5_image(w, h, data):
    hdr = (struct.pack('<4sIIIIIII44s', b'DDS ', 124, 0x1007 | 0x80000, h, w, len(data), 0, 1, b'\0' * 44) +
           struct.pack('<II4sIIIII', 32, 4, b'DXT5', 0, 0, 0, 0, 0) + struct.pack('<IIIII', 0x1000, 0, 0, 0, 0))
    return Image.open(io.BytesIO(hdr + data)).convert('RGBA')

p = Pkg(sys.argv[1]); d = p.d
tex = {}
for i, e in enumerate(p.exports):
    b = d[e['off']:e['off'] + e['size']]
    try:
        pr, o = props(p, b, 4)
        if pr.get('Format') != 'PF_DXT5': continue
        w, h, data = mip0(b, o)
        bb = dxt5_image(w, h, data).getchannel('A').point(lambda a: 255 if a > 20 else 0).getbbox() or (0, 0, w, h)
        tex[full(p, i)] = (fnv(data[:w * h]), w, h, bb)
    except Exception:
        pass
PS = {'bottom': 'Callouts.callout_bottom_btn', 'left': 'Callouts.callout_left_btn', 'right': 'Callouts.callout_right_btn',
      'top': 'Callouts.top_btn', 'L1': 'Callouts.callout_L1_btn', 'L2': 'Callouts.callout_L2_btn', 'R1': 'Callouts.callout_R1_btn',
      'R2': 'Callouts.callout_R2_btn', 'L3': 'Callouts.callout_L3_btn', 'R3': 'Callouts.callout_R3_btn',
      'LStick': 'Callouts.callout_LStick_btn', 'RStick': 'Callouts.callout_RStick_btn', 'naLStick': 'Callouts.callout_LStick_btn',
      'mvStck': 'Callouts.callout_moveStck_btn', 'mvStck_lft': 'Callouts.callout_moveLft_btn', 'mvStck_rght': 'Callouts.callout_moveRght_btn',
      'thmbstck': 'Callouts.callout_thmbstick_btn', 'pr_stck': 'Callouts.callout_thmbPress_btn', 'dpad': 'Callouts.callout_dpad_btn',
      'select': 'Callouts.callout_select_btn', 'start': 'Callouts.callout_start_btn'}
print('// generated by tools/re/buttonicons.py from the game\'s UI_ButtonIcons.upk - do not edit')
print('// xbox / ps = FNV-1a of the top mip (DXT5) as the game uploads it; dst = where the PS art goes in the Xbox')
print('// texture (fractions, aspect kept), src = the PS art\'s used area (uv)')
print('struct BtnIcon { uint32_t xbox, ps; float dst[4], src[4]; const char* name; };')
print('static const BtnIcon kBtnIcons[] = {')
seen = set()
for n in sorted(tex):
    m = re.match(r'(?:Generic\.|PDA\.)?gp_(?:callout|dss|csa|pda)_(.+?)_(?:btn|gen)(?:_gen)?$', n)
    if not m: continue
    key = m.group(1)
    if key not in PS or PS[key] not in tex: continue
    xh, xw, xhh, xb = tex[n]; ph, pw, phh, pb = tex[PS[key]]
    if xh in seen: continue
    seen.add(xh)
    # fit the PS content box into the Xbox content box, keeping its aspect
    dw, dh = xb[2] - xb[0], xb[3] - xb[1]; sw, sh = pb[2] - pb[0], pb[3] - pb[1]
    s = min(dw / sw, dh / sh); fw, fh = sw * s, sh * s
    fx, fy = xb[0] + (dw - fw) / 2, xb[1] + (dh - fh) / 2
    dst = (fx / xw, fy / xhh, fw / xw, fh / xhh); src = (pb[0] / pw, pb[1] / phh, sw / pw, sh / phh)
    print('    { 0x%08xu, 0x%08xu, { %.4ff, %.4ff, %.4ff, %.4ff }, { %.4ff, %.4ff, %.4ff, %.4ff }, "%s" },' % ((xh, ph) + dst + src + (n,)))
print('};')
