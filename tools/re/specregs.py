# Finds the specular-exponent constant registers of skin / metal light-pass shaders in the shader
# cache: pow(x, e) compiles to log/mul/exp; the specular one has its base from a max() (max(R.V, eps)),
# the Fresnel one from 1 - x (add). The exponent is either a constant register or a lerp of two
# (SpecularPowerMin/Max by a texture) - all constant registers in that small chain are collected.
# usage: AP_SHADERCACHE=.../RefShaderCache-PC-D3D-SM3.upk python3 -I specregs.py > ../../src/specregs.h
import sys,os,re,struct,collections
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
import shadercache as sc
OPN={1:'mov',2:'add',4:'mad',5:'mul',10:'min',11:'max',14:'exp',15:'log',18:'lrp',88:'cmp',8:'dp3',9:'dp4'}
def instrs(code_off):
    c=sc.c; i=code_off+4; out=[]
    while True:
        tok=struct.unpack_from('<I',c,i)[0]
        if tok==0xFFFF: break
        op=tok&0xFFFF
        if op==0xFFFE: i+=4+((tok>>16)&0x7FFF)*4; continue
        ln=(tok>>24)&0xF
        a=list(struct.unpack_from('<%dI'%ln,c,i+4)) if ln else []
        out.append((op,a)); i+=4+ln*4
    return out
def reg(t): return (((t>>28)&7)|((t>>8)&0x18), t&0x7FF)
def wmask(t): return (t>>16)&0xF
def swz_comps(t):
    s=(t>>16)&0xFF; return {(s>>(2*k))&3 for k in range(4)}
def comp(mask): return [k for k in range(4) if mask>>k&1]
def writer(ins, idx, r, comps):
    for j in range(idx-1,-1,-1):
        op,a=ins[j]
        if op in (31,81,0x2F,0x30) or not a: continue
        if reg(a[0])==r and (wmask(a[0]) & sum(1<<k for k in comps)): return j
    return -1
def consts_in_slice(ins, idx, r, comps, depth=4, seen=None):
    out=set()
    if depth<0: return out
    j=writer(ins, idx, r, comps)
    if j<0: return out
    op,a=ins[j]
    for t in a[1:]:
        ty,n=reg(t)
        if ty==2: out.add(n)
        elif ty==0: out|=consts_in_slice(ins,j,(0,n),swz_comps(t),depth-1)
    return out
def analyse(code_off, defs):
    ins=instrs(code_off); found=set()
    for k,(op,a) in enumerate(ins):
        if op!=15 or k+3>=len(ins): continue   # log
        dst=reg(a[0]); src=a[1]
        bj=writer(ins,k,reg(src),swz_comps(src))
        if bj<0 or ins[bj][0]!=11: continue    # base must come from max()
        # follow the log result (through the cmp that guards log(0)) to the mul that scales it before exp
        track=dst
        for m in range(k+1,min(k+12,len(ins))):
            op2,b=ins[m]
            if not b: continue
            if op2==88 and any(reg(t)==track for t in b[1:]): track=reg(b[0]); continue
            if op2==5 and any(reg(t)==track for t in b[1:]) and m+1<len(ins) and ins[m+1][0]==14:
                for t in b[1:]:
                    ty,n=reg(t)
                    if ty==2: found.add(n)
                    elif ty==0 and (0,n)!=track: found|=consts_in_slice(ins,m,(0,n),swz_comps(t))
                break
    return sorted(r for r in found if r not in defs)
def defregs(code_off):
    return {reg(a[0])[1] for op,a in instrs(code_off) if op==81}
if __name__=='__main__':
    import re as _re
    cls={}
    for n,g,l in sc.material_maps():
        k='skin' if _re.search(r'skin',n,_re.I) and not _re.search(r'skinned',n,_re.I) else \
          'metal' if _re.search(r'^MASTER_Weapon|^MASTER_BasicVehicleWeapon|^AP_Weapon_Master$|^Weapons_MST_MAT$|metal|chrome|steel|^Pipes|Chains|ShellCasing|ShotgunShell|^Shotgun_',n,_re.I) else None
        if not k: continue
        for st,h in l:
            if st.startswith('TLightPixelShader'): cls.setdefault(h,set()).add(k)
    S=sc.shaders(); byh={v[1]:v for v in S.values()}
    rows=[]
    for h,ks in sorted(cls.items()):
        if len(ks)!=1 or h not in byh: continue
        off=byh[h][2]
        regs=analyse(off, defregs(off))
        if 1<=len(regs)<=3: rows.append((h, 1 if 'skin' in ks else 2, regs))
    print('// Generated by tools/re/specregs.py: specular-exponent constant registers of skin (1) / metal (2)')
    print('// light-pass pixel shaders, by bytecode hash. Sorted by hash.')
    print('#pragma once\n#include <cstdint>')
    print('struct SpecRegs { uint32_t hash; uint8_t kind, n, r[3]; };')
    print('static const SpecRegs kSpecRegs[%d] = {'%len(rows))
    for h,k,r in rows:
        rr=(r+[0,0,0])[:3]
        print('    { 0x%08xu, %d, %d, { %d, %d, %d } },'%(h,k,len(r),rr[0],rr[1],rr[2]))
    print('};')
    sys.stderr.write('rows %d (skin %d metal %d)\n'%(len(rows),sum(1 for x in rows if x[1]==1),sum(1 for x in rows if x[1]==2)))
